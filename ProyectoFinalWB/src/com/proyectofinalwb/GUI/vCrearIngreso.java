    public double obtenerDouble(JTextField jt) {
        try {
            return Double.parseDouble(jt.getText().trim());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(null, "Por favor ingrese un número válido");
            this.jtfSalario.setText(""); // Limpiar campo
            this.jtfSalario.requestFocus(); // Volver al campo
            return 0.0; // o lanzar excepción
        }
    }

