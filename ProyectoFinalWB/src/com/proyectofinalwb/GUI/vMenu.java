    public void actualizarTabla() {
        u.obtenerPresupuestos(new Presupuesto(u.getId()));
        
        javax.swing.table.DefaultTableModel model
                = (javax.swing.table.DefaultTableModel) presupuestos.getModel();
        model.setRowCount(0);

        
        for (int i = 0; i < u.getPresupuestos().size(); i++) {
 
            model.addRow(new Object[]{
                u.getPresupuestos().get(i).totalGastos(u.getPresupuestos().get(i).getGastos()),
                u.getPresupuestos().get(i).totalLibre(),
                u.getPresupuestos().get(i).getLimite(),
                u.getPresupuestos().get(i).getMeta()
            });
        }
        
    }

