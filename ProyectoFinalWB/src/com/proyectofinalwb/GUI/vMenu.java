    private void botonAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonAgregarActionPerformed
        try {

            out.writeUTF("PRESUPUESTO");
            out.flush();
            Presupuesto p = new Presupuesto(this.u.getId());
            out.writeObject(p);
            out.flush();
            
            boolean confirmacion = in.readBoolean();

            if (confirmacion) {
                vCrearPresupuesto vcp = new vCrearPresupuesto(this, socket, in, out, p);
                this.setVisible(false);
                vcp.setVisible(true);
            } else {
                JOptionPane.showMessageDialog(rootPane, "Error al crear presupuesto 1");
            }
        } catch (IOException ex) {
            JOptionPane.showMessageDialog(rootPane, "Error a insertar presupuesto 1");
        }

    }//GEN-LAST:event_botonAgregarActionPerformed

    private void botonCerrarSesionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonCerrarSesionActionPerformed
        
        JOptionPane.showMessageDialog(rootPane, "Cerrando sesión...");
        this.dispose();
        
        try {
            out.writeUTF("INICIAR");
            out.flush();
        } catch (IOException ex) {
            JOptionPane.showMessageDialog(rootPane, "ERROR AL SALIR");
        }
        this.v.setVisible(true);
    }//GEN-LAST:event_botonCerrarSesionActionPerformed

