    public void actualizar() {
        this.model1.setRowCount(0);
        this.model2.setRowCount(0);

        p.getGastos().clear();
        p.getIngresos().clear();

        Gasto v = new Variable(p.getId());
        Gasto f = new Fijo(p.getId());
        Gasto d = new Discrecional(p.getId());

        p.obtenerIngresos(new Ingreso(p.getId()));

        p.getGastos().clear();
        p.obtenerGastos(v);
        p.obtenerGastos(f);
        p.obtenerGastos(d);

        for (int i = 0; i < p.getGastos().size(); ++i) {
            model1.addRow(new Object[]{
                p.getGastos().get(i).tipoDeGasto(),
                p.getGastos().get(i).getNombre(),
                p.getGastos().get(i).getMonto(),});
        }
        for (int i = 0; i < p.getIngresos().size(); i++) {
            model2.addRow(new Object[]{
                p.getIngresos().get(i).getTipoDeIngreso(),
                p.getIngresos().get(i).getSalarioNeto()
            });
        }

    }
