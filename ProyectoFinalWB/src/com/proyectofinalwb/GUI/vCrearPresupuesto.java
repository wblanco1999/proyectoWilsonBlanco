    private void botonGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonGuardarActionPerformed
        try {
            double meta = Double.parseDouble(this.jtfMeta.getText().trim());
            double limite = Double.parseDouble(this.jtfLimite.getText().trim());

            out.writeUTF("PRESUPUESTO-MOD");
            out.flush();

            out.writeObject(new Presupuesto(p.getId(), p.getUsuarioId(), limite, meta));

            out.flush();

            boolean confirmar = in.readBoolean();

            if (confirmar) {
                JOptionPane.showMessageDialog(this, "Presupuesto guardado con éxito");
                this.dispose();
                this.vi.setVisible(true);
                vi.actualizarTabla();
            } else {
                JOptionPane.showMessageDialog(this, "No se pudo guardar el presupuesto");
            }
        } catch (NumberFormatException nfe) {
            JOptionPane.showMessageDialog(this, "Ingrese valores numéricos válidos en Meta y Límite");
        } catch (IOException ex) {
            JOptionPane.showMessageDialog(this, "Error de comunicación con el servidor: " + ex.getMessage());
        }

    }//GEN-LAST:event_botonGuardarActionPerformed

