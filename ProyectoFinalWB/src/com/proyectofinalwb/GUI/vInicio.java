    private void botonIniciarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonIniciarActionPerformed
        Socket vNuevo;
        try {
            vNuevo = new Socket("localhost", 9997);
            ObjectOutputStream vOutput = new ObjectOutputStream(vNuevo.getOutputStream());
            vOutput.flush();
            ObjectInputStream vInput = new ObjectInputStream(vNuevo.getInputStream());

            InetAddress ip = InetAddress.getLocalHost();
            vOutput.writeUTF("Dirección IP: " + ip);
            vOutput.flush();
            vOutput.writeUTF("INICIAR");
            vOutput.flush();
            this.setVisible(false);
            vInicioSesion vi = new vInicioSesion(this, vNuevo, vInput, vOutput);
            vi.setVisible(true);
            this.setVisible(false);
        } catch (Exception e) {
        }
    }//GEN-LAST:event_botonIniciarActionPerformed

