    private void botonIniciarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonIniciarActionPerformed
        
        try{
            Usuario u = new Usuario(this.jtfUsuario.getText(), this.jtfpasswd.getText());
            out.writeObject(u);
            out.flush();
            String resultado = in.readUTF();
            u = (Usuario) in.readObject();
            if(resultado.equals("")){
                JOptionPane.showMessageDialog(rootPane, "No se ha encontrado ningún usuario");
                out.writeUTF("INICIAR");
                out.flush();
                this.jtfUsuario.setText("");
                this.jtfpasswd.setText("");
            }else{
                JOptionPane.showMessageDialog(rootPane, resultado);
                this.setVisible(false);
                vMenu vm = new vMenu(this, this.socket, this.in, this.out, u);
                vm.setVisible(true);
                vm.getLblBienvenido().setText("Bienvenido " + u.getUsername());
                this.jtfUsuario.setText("");
                this.jtfpasswd.setText("");
            }
        }
        catch(Exception ex){
            
        }
    }//GEN-LAST:event_botonIniciarActionPerformed

