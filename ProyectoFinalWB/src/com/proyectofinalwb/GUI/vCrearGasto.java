    private boolean comprobarBoolean(String s) {
        if (s.equals("SI")) {
            return true;
        } else {
            return false;
        }
    }

    private Prioridad cambiarPrioridad(String s) {
        if (s == null) {
            return Prioridad.MEDIA; // o el valor por defecto que prefieras
        }

        String prioridadNormalizada = s.trim().toUpperCase();

        switch (prioridadNormalizada) {
            case "URGENTE":
            case "URGENT":
            case "CRITICA":
            case "CRITICAL":
                return Prioridad.URGENTE;

            case "ALTA":
            case "HIGH":
                return Prioridad.ALTA;

            case "MEDIA":
            case "MEDIUM":
            case "NORMAL":
                return Prioridad.MEDIA;

            case "BAJA":
            case "LOW":
                return Prioridad.BAJA;

            default:
                return Prioridad.MEDIA; // Valor por defecto
        }
    }

    private Periocidad cambiarPeriocidad(String s) {
        if (s == null || s.trim().isEmpty()) {
            return Periocidad.MENSUAL;
        }

        String periocidadNormalizada = s.trim().toUpperCase();

        switch (periocidadNormalizada) {
            case "DIARIA":
            case "DIARIO":
            case "DAILY":
                return Periocidad.DIARIA;

            case "SEMANAL":
            case "SEMANA":
            case "WEEKLY":
                return Periocidad.SEMANAL;

            case "QUINCENAL":
            case "QUINCENA":
            case "BIWEEKLY":
                return Periocidad.QUINCENAL;

            case "MENSUAL":
            case "MES":
            case "MONTHLY":
                return Periocidad.MENSUAL;

            case "ANUAL":
            case "AÑO":
            case "YEARLY":
            case "ANNUAL":
                return Periocidad.ANUAL;

            case "SEMESTRE":
            case "SEMESTRAL":
            case "BIANUAL":
            case "BIANNUAL":
                return Periocidad.SEMESTRE;

            default:
                return Periocidad.MENSUAL; // Valor por defecto
        }
    }

    private void agregarGastoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_agregarGastoActionPerformed

        try {
            out.writeUTF("GASTO");
            out.flush();
            if (categoriaGasto.getSelectedItem().toString().equals("Fijo")) {
//             boolean caducidad, int plazo, Prioridad prioridad, String presupuestoId, String nombre, double monto, Periocidad periocidad
                Fijo f = new Fijo(
                        comprobarBoolean(this.si_no.getSelectedItem().toString()),
                        Integer.parseInt(this.field1.getText().trim()),
                        cambiarPrioridad(this.prioridad.getSelectedItem().toString()),
                        this.id,
                        this.nombre.getText(),
                        Double.parseDouble(this.monto.getText().trim()),
                        cambiarPeriocidad(this.periocidad.getSelectedItem().toString())
                );
                out.writeObject(f);
                out.flush();

                boolean confirmacion = in.readBoolean();
                if (confirmacion) {
//                    javax.swing.table.DefaultTableModel model
//                            = (javax.swing.table.DefaultTableModel) jTable1.getModel();
//                    model.setRowCount(0);
                 
                    model.addRow(new Object[]{
                        f.getNombre(),
                        f.getMonto(),});
                    this.monto.setText("");
                    this.nombre.setText("");
                    this.field1.setText("");

                }
            } else if (categoriaGasto.getSelectedItem().toString().equals("Variable")) {
//                presupuestoMax, Prioridad prioridad, boolean temporadaAlta, String nombre, double monto, Periocidad periocidad, String presupuestoId)
                Variable v = new Variable(
                        Double.parseDouble(this.field1.getText()),
                        cambiarPrioridad(this.prioridad.getSelectedItem().toString()),
                        comprobarBoolean(this.si_no.getSelectedItem().toString()),
                        this.nombre.getText(),
                        Double.parseDouble(this.monto.getText().trim()),
                        cambiarPeriocidad(this.periocidad.getSelectedItem().toString()),
                        this.id
                );
                out.writeObject(v);
                out.flush();
                boolean confirmacion = in.readBoolean();
                if (confirmacion) {
                    model.addRow(new Object[]{
                        v.getNombre(),
                        v.getMonto(),});
                    this.monto.setText("");
                    this.nombre.setText("");
                    this.field1.setText("");
                }
            } else if (categoriaGasto.getSelectedItem().toString().equals("Discrecional")) {
                Discrecional d = new Discrecional(
                        comprobarBoolean(this.si_no.getSelectedItem().toString()),
                        this.field1.getText(),
                        this.descripcion.getText(),
                        this.nombre.getText(),
                        Double.parseDouble(this.monto.getText().trim()),
                        cambiarPeriocidad(this.periocidad.getSelectedItem().toString()),
                        this.id
                );
                out.writeObject(d);
                out.flush();
                boolean confirmacion = in.readBoolean();
                if (confirmacion) {                 
                    model.addRow(new Object[]{
                        d.getNombre(),
                        d.getMonto(),});
                    this.monto.setText("");
                    this.nombre.setText("");
                    this.field1.setText("");
                    this.descripcion.setText("");
                }
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(rootPane, "Error al insertar");
        }
    }//GEN-LAST:event_agregarGastoActionPerformed

